namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for bootstrap label style.
    /// </summary>
    public enum BootstrapLabelStyle : int
    {
        /// <summary>
        ///     Represents the label above BootstrapBuilder option.
        /// </summary>
        LabelAbove,

        /// <summary>
        ///     Represents the label before BootstrapBuilder option.
        /// </summary>
        LabelBefore,

        /// <summary>
        ///     Represents the label group BootstrapBuilder option.
        /// </summary>
        LabelGroup,

        /// <summary>
        ///     Represents the label floating BootstrapBuilder option.
        /// </summary>
        LabelFloating,

        /// <summary>
        ///     Represents the no label BootstrapBuilder option.
        /// </summary>
        NoLabel
    }
}