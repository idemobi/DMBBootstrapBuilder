namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for side bar theme.
    /// </summary>
    public enum SideBarTheme
    {
        /// <summary>
        ///     Uses the default BootstrapBuilder or Bootstrap behavior.
        /// </summary>
        Default,

        /// <summary>
        ///     Represents the light BootstrapBuilder option.
        /// </summary>
        Light,

        /// <summary>
        ///     Represents the dark BootstrapBuilder option.
        /// </summary>
        Dark,

        /// <summary>
        ///     Represents the transparent BootstrapBuilder option.
        /// </summary>
        Transparent,

        /// <summary>
        ///     Represents the colored BootstrapBuilder option.
        /// </summary>
        Colored,

        /// <summary>
        ///     Represents the primary BootstrapBuilder option.
        /// </summary>
        Primary,

        /// <summary>
        ///     Represents the inversed BootstrapBuilder option.
        /// </summary>
        Inversed
    }
}