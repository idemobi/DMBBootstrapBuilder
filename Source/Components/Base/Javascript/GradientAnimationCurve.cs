namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for gradient animation curve.
    /// </summary>
    public enum GradientAnimationCurve
    {
        /// <summary>
        ///     Represents the linear BootstrapBuilder option.
        /// </summary>
        Linear = 0,

        /// <summary>
        ///     Represents the ease BootstrapBuilder option.
        /// </summary>
        Ease = 1,

        /// <summary>
        ///     Represents the ease in BootstrapBuilder option.
        /// </summary>
        EaseIn = 2,

        /// <summary>
        ///     Represents the ease out BootstrapBuilder option.
        /// </summary>
        EaseOut = 3,

        /// <summary>
        ///     Represents the ease in out BootstrapBuilder option.
        /// </summary>
        EaseInOut = 4
    }
}