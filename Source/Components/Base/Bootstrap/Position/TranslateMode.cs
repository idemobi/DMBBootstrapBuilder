namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for translate mode.
    /// </summary>
    public enum TranslateMode
    {
        /// <summary>
        ///     Disables the related BootstrapBuilder option.
        /// </summary>
        None,

        /// <summary>
        ///     Represents the middle BootstrapBuilder option.
        /// </summary>
        Middle,

        /// <summary>
        ///     Represents the middle x BootstrapBuilder option.
        /// </summary>
        MiddleX,

        /// <summary>
        ///     Represents the middle y BootstrapBuilder option.
        /// </summary>
        MiddleY
    }
}