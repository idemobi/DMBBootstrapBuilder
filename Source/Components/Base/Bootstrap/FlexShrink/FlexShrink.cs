namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for flex shrink.
    /// </summary>
    public enum FlexShrink
    {
        /// <summary>
        ///     Disables the related BootstrapBuilder option.
        /// </summary>
        None,

        /// <summary>
        ///     Represents the shrink BootstrapBuilder option.
        /// </summary>
        Shrink,

        /// <summary>
        ///     Represents the no shrink BootstrapBuilder option.
        /// </summary>
        NoShrink
    }
}