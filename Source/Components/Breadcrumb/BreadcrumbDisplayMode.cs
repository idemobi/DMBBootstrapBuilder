namespace DMBBootstrapBuilder;

/// <summary>
///     Defines BootstrapBuilder values for breadcrumb display mode.
/// </summary>
public enum BreadcrumbDisplayMode
{
    /// <summary>
    ///     Represents the title only BootstrapBuilder option.
    /// </summary>
    TitleOnly,

    /// <summary>
    ///     Represents the icon only BootstrapBuilder option.
    /// </summary>
    IconOnly,

    /// <summary>
    ///     Represents the icon and title BootstrapBuilder option.
    /// </summary>
    IconAndTitle
}