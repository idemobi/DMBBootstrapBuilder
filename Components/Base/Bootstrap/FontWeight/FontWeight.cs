namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for font weight.
    /// </summary>
    public enum FontWeight
    {
        /// <summary>
        ///     Disables the related BootstrapBuilder option.
        /// </summary>
        None = 0,

        /// <summary>
        ///     Represents the bold BootstrapBuilder option.
        /// </summary>
        Bold,

        /// <summary>
        ///     Represents the bolder BootstrapBuilder option.
        /// </summary>
        Bolder,

        /// <summary>
        ///     Represents the semi bold BootstrapBuilder option.
        /// </summary>
        SemiBold,

        /// <summary>
        ///     Represents the normal BootstrapBuilder option.
        /// </summary>
        Normal,

        /// <summary>
        ///     Represents the medium BootstrapBuilder option.
        /// </summary>
        Medium,

        /// <summary>
        ///     Represents the light BootstrapBuilder option.
        /// </summary>
        Light,

        /// <summary>
        ///     Represents the lighter BootstrapBuilder option.
        /// </summary>
        Lighter,
    }
}