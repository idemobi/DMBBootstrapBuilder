namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for display.
    /// </summary>
    public enum Display
    {
        /// <summary>
        ///     Disables the related BootstrapBuilder option.
        /// </summary>
        None,

        /// <summary>
        ///     Represents the inline BootstrapBuilder option.
        /// </summary>
        Inline,

        /// <summary>
        ///     Represents the inline block BootstrapBuilder option.
        /// </summary>
        InlineBlock,

        /// <summary>
        ///     Represents the block BootstrapBuilder option.
        /// </summary>
        Block,

        /// <summary>
        ///     Represents the grid BootstrapBuilder option.
        /// </summary>
        Grid,

        /// <summary>
        ///     Represents the inline grid BootstrapBuilder option.
        /// </summary>
        InlineGrid,

        /// <summary>
        ///     Represents the table BootstrapBuilder option.
        /// </summary>
        Table,

        /// <summary>
        ///     Represents the table row BootstrapBuilder option.
        /// </summary>
        TableRow,

        /// <summary>
        ///     Represents the table cell BootstrapBuilder option.
        /// </summary>
        TableCell,

        /// <summary>
        ///     Represents the flex BootstrapBuilder option.
        /// </summary>
        Flex,

        /// <summary>
        ///     Represents the inline flex BootstrapBuilder option.
        /// </summary>
        InlineFlex
    }
}