namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for text decoration.
    /// </summary>
    public enum TextDecoration
    {
        /// <summary>
        ///     Disables the related BootstrapBuilder option.
        /// </summary>
        None = 0,

        /// <summary>
        ///     Represents the underline BootstrapBuilder option.
        /// </summary>
        Underline,

        /// <summary>
        ///     Represents the line through BootstrapBuilder option.
        /// </summary>
        LineThrough,

        /// <summary>
        ///     Represents the cancel decoration BootstrapBuilder option.
        /// </summary>
        CancelDecoration
    }
}