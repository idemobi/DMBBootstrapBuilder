namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for flex direction.
    /// </summary>
    public enum FlexDirection
    {
        /// <summary>
        ///     Represents the row BootstrapBuilder option.
        /// </summary>
        Row,

        /// <summary>
        ///     Represents the row reverse BootstrapBuilder option.
        /// </summary>
        RowReverse,

        /// <summary>
        ///     Represents the column BootstrapBuilder option.
        /// </summary>
        Column,

        /// <summary>
        ///     Represents the column reverse BootstrapBuilder option.
        /// </summary>
        ColumnReverse
    }
}