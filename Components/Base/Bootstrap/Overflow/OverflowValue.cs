namespace DMBBootstrapBuilder
{
    /// <summary>
    /// Defines BootstrapBuilder values for overflow value.
    /// </summary>
    public enum OverflowValue
    {
        /// <summary>
        /// Disables the related BootstrapBuilder option.
        /// </summary>
        None,
        /// <summary>
        /// Represents the auto BootstrapBuilder option.
        /// </summary>
        Auto,
        /// <summary>
        /// Represents the hidden BootstrapBuilder option.
        /// </summary>
        Hidden,
        /// <summary>
        /// Represents the visible BootstrapBuilder option.
        /// </summary>
        Visible,
        /// <summary>
        /// Represents the scroll BootstrapBuilder option.
        /// </summary>
        Scroll
    }
}