namespace DMBBootstrapBuilder
{
    /// <summary>
    ///     Defines BootstrapBuilder values for border radius size.
    /// </summary>
    public enum BorderRadiusSize
    {
        /// <summary>
        ///     Disables the related BootstrapBuilder option.
        /// </summary>
        None,

        /// <summary>
        ///     Represents the small BootstrapBuilder option.
        /// </summary>
        Small,

        /// <summary>
        ///     Represents the normal BootstrapBuilder option.
        /// </summary>
        Normal,

        /// <summary>
        ///     Represents the large BootstrapBuilder option.
        /// </summary>
        Large,

        /// <summary>
        ///     Represents the extra large BootstrapBuilder option.
        /// </summary>
        ExtraLarge,

        /// <summary>
        ///     Represents the extra extra large BootstrapBuilder option.
        /// </summary>
        ExtraExtraLarge,

        /// <summary>
        ///     Represents the circle BootstrapBuilder option.
        /// </summary>
        Circle,

        /// <summary>
        ///     Represents the pill BootstrapBuilder option.
        /// </summary>
        Pill
    }
}