namespace DMBBootstrapBuilder
{
    /// <summary>
    /// Defines BootstrapBuilder values for border opacity.
    /// </summary>
    public enum BorderOpacity
    {
        /// <summary>
        /// Disables the related BootstrapBuilder option.
        /// </summary>
        None,
        /// <summary>
        /// Represents the opacity10 BootstrapBuilder option.
        /// </summary>
        Opacity10,
        /// <summary>
        /// Represents the opacity25 BootstrapBuilder option.
        /// </summary>
        Opacity25,
        /// <summary>
        /// Represents the opacity50 BootstrapBuilder option.
        /// </summary>
        Opacity50,
        /// <summary>
        /// Represents the opacity75 BootstrapBuilder option.
        /// </summary>
        Opacity75,
        /// <summary>
        /// Represents the opacity100 BootstrapBuilder option.
        /// </summary>
        Opacity100
    }
}